def binding_refund(rng: random.Random, split: str):
    amount = money(rng)
    order_id = order(rng)
    item = product(rng)
    why = reason(rng)
    customer = pick(
        rng,
        split,
        (
            f"Hi, my {item} from order #{order_id} {why}. Can I get a refund?",
            f"The {item} I ordered (#{order_id}) {why}. I would like my money back.",
        ),
        (
            f"My {item} arrived and {why}. Order #{order_id}. What can you do?",
            f"I need help with order #{order_id}. The {item} {why}.",
        ),
    )
    reply = pick(
        rng,
        split,
        (
            f"I am sorry about that. I have processed a full {amount} refund for order #{order_id}. {timeline(rng)}",
            f"I have issued a {amount} refund to your original payment method. {timeline(rng)}",
            f"I have approved the {amount} refund for order #{order_id}. {timeline(rng)}",
        ),
        (
            f"The {amount} refund for order #{order_id} is complete. {timeline(rng)}",
            f"I have sent a {amount} refund back to your card. {timeline(rng)}",
            f"Your {amount} refund has been issued. {timeline(rng)}",
        ),
    )
    return [("customer", customer), ("agent", reply)], True, "binding"


