"""Generate labeled transcripts for a local promise gate fine-tune.

The rows use the `laya.train` schema: `{state, questions, expected}`. Labels are
constructed by scenario, not generated by a model, so the training signal is
exact. Train rows and held-out rows use different phrasings to make the test a
real test rather than a memorization check.

The gate question is deliberately narrower than "is there any money word":
`needs_extraction` is true only when the agent committed to a financial action
(binding, conditional, superseded, or retracted). Policy explanations and status
updates are `info_only` and should be skipped by the gate. The modality head
still has to tell those five states apart.
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

MODALITIES = (
    "binding",
    "conditional",
    "superseded",
    "retracted",
    "info_only",
)

QUESTIONS = {
    "needs_extraction": {
        "type": "noul",
        "instructions": (
            "The agent committed to moving money or changing an order financially: "
            "a refund, credit, discount, cancellation, or compensation that is done "
            "or will be done. Policy explanations, status updates, and requests for "
            "information do not count."
        ),
    },
    "modality": {
        "type": "choice",
        "instructions": (
            "At the end of the transcript, what is the state of the agent's original "
            "financial commitment?"
        ),
        "criteria": {
            "binding": "An unconditional commitment that still stands.",
            "conditional": "Depends on a future customer action.",
            "superseded": "A later turn replaced it with a different amount or action.",
            "retracted": "The agent took it back.",
            "info_only": "Policy explanation or status update, never a commitment.",
        },
    },
}

NAMES = ("Maya", "Alex", "Sam", "Jordan", "Priya", "Diego", "Noah", "Lena")
PRODUCTS = (
    "mug",
    "headphones",
    "lamp",
    "jacket",
    "backpack",
    "blender",
    "keyboard",
    "sneakers",
    "monitor",
    "candle",
    "kettle",
    "desk chair",
)
REASONS = (
    "arrived cracked",
    "stopped working",
    "was the wrong color",
    "never arrived",
    "was damaged in transit",
    "is missing a part",
    "does not fit",
    "was delivered late",
    "arrived used",
)
AMOUNTS = (15, 18.5, 20, 24.99, 30, 35, 40, 45, 45.5, 50, 60, 75, 89.99, 120)
TIMELINES = (
    "It should appear on your statement in 5 to 10 business days.",
    "You will see it within 3 to 5 business days.",
    "The funds usually post in about a week.",
    "Your bank may take a few days to show it.",
)
GREETINGS = ("Hi", "Hello", "Hey", "Good morning")
CLOSINGS = (
    "Thanks for your patience.",
    "Let me know if you need anything else.",
    "Have a good day.",
    "I appreciate your patience.",
)


def pick(rng: random.Random, split: str, train: tuple[str, ...], heldout: tuple[str, ...]) -> str:
    return rng.choice(train if split == "train" else heldout)


def money(rng: random.Random) -> str:
    amount = rng.choice(AMOUNTS)
    return f"${amount:.2f}" if isinstance(amount, float) else f"${amount}"


def order(rng: random.Random) -> int:
    return rng.randint(1001, 9999)


def agent_name(rng: random.Random) -> str:
    return rng.choice(NAMES)


def product(rng: random.Random) -> str:
    return rng.choice(PRODUCTS)


def reason(rng: random.Random) -> str:
    return rng.choice(REASONS)


def timeline(rng: random.Random) -> str:
    return rng.choice(TIMELINES)


def closing(rng: random.Random) -> str:
    return rng.choice(CLOSINGS)


def greet(rng: random.Random) -> str:
    return f"{rng.choice(GREETINGS)}!"


def maybe_noise(rng: random.Random, turns: list[tuple[str, str]]) -> list[tuple[str, str]]:
    """Add a greeting or closing to make the commitment harder to spot."""
    out = list(turns)
    if rng.random() < 0.35:
        out.insert(0, ("customer", f"{greet(rng)} I need help with an order."))
    if rng.random() < 0.35:
        out.append(("customer", closing(rng)))
    return out


def render(turns: list[tuple[str, str]]) -> str:
    return "\n".join(f"{role}: {text}" for role, text in turns)


def make_row(
    rng: random.Random,
    family: str,
    turns: list[tuple[str, str]],
    needs: bool,
    modality: str,
    index: int,
) -> dict:
    if modality not in MODALITIES:
        raise ValueError(f"unknown modality {modality!r}")
    if needs != (modality != "info_only"):
        raise ValueError(f"label mismatch in {family}: needs={needs} modality={modality}")
    return {
        "case": f"{family}-{index:03d}",
        "family": family,
        "state": render(maybe_noise(rng, turns)),
        "questions": QUESTIONS,
        "expected": {"needs_extraction": needs, "modality": modality},
    }


