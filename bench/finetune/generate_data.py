def generate(split: str, per_family: int, seed: int) -> list[dict]:
    rng = random.Random(seed)
    rows: list[dict] = []
    seen: set[str] = set()
    for family_index, scenario in enumerate(SCENARIOS):
        made = 0
        attempts = 0
        while made < per_family and attempts < per_family * 20:
            attempts += 1
            turns, needs, modality = scenario(rng, split)
            row = make_row(
                rng,
                scenario.__name__,
                turns,
                needs,
                modality,
                family_index * 1000 + made,
            )
            if row["state"] in seen:
                continue
            seen.add(row["state"])
            rows.append(row)
            made += 1
        if made < per_family:
            raise RuntimeError(f"{scenario.__name__} produced only {made} unique rows")
    rng.shuffle(rows)
    return rows


def write_jsonl(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate gate fine-tuning data.")
    parser.add_argument("--out", default="data", help="output directory")
    parser.add_argument("--train-per-family", type=int, default=20)
    parser.add_argument("--val-per-family", type=int, default=5)
    parser.add_argument("--test-per-family", type=int, default=5)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    out = Path(args.out)
    train = generate("train", args.train_per_family, args.seed)
    val = generate("heldout", args.val_per_family, args.seed + 1)
    test = generate("heldout", args.test_per_family, args.seed + 2)
    write_jsonl(out / "train.jsonl", train)
    write_jsonl(out / "val.jsonl", val)
    write_jsonl(out / "test.jsonl", test)

    from collections import Counter

    for name, rows in (("train", train), ("val", val), ("test", test)):
        labels = Counter((r["expected"]["needs_extraction"], r["expected"]["modality"]) for r in rows)
        print(f"{name}: {len(rows)} rows")
        for label, count in sorted(labels.items(), key=lambda item: (str(item[0][0]), item[0][1])):
            print(f"  needs={label[0]} modality={label[1]}: {count}")


if __name__ == "__main__":
    main()
